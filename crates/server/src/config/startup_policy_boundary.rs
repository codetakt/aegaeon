pub(super) fn configured_startup_managed_policy_env_keys() -> Result<Vec<&'static str>, ConfigError>
{
    STARTUP_MANAGED_POLICY_ENV_KEYS
        .iter()
        .map(|key| env_key_is_present(key).map(|configured| (*key, configured)))
        .filter_map(|result| match result {
            Ok((key, true)) => Some(Ok(key)),
            Ok((_key, false)) => None,
            Err(err) => Some(Err(err)),
        })
        .collect()
}
