#!/usr/bin/env python3
"""Reproduce the LTI zoneinfo identifier table from pinned IANA bytes, offline."""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import re
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "crates/server/data/time-zones"
OUTPUT = ROOT / "crates/server/src/lti/claims/standard/time_zones.rs"


def render(raw: bytes | None = None) -> str:
    source = json.loads((DATA / "source.json").read_text())
    payload = (DATA / "tzdata2026f.tar.gz").read_bytes() if raw is None else raw
    if hashlib.sha256(payload).hexdigest() != source["sha256"]:
        message = "IANA archive digest mismatch"
        raise ValueError(message)
    names: set[str] = set()
    with tarfile.open(fileobj=io.BytesIO(payload), mode="r:gz") as archive:
        for member, digest in source["members_sha256"].items():
            item = archive.getmember(member)
            if not item.isfile() or item.size > 2 * 1024 * 1024:
                message = "unsupported IANA member"
                raise ValueError(message)
            stream = archive.extractfile(item)
            if stream is None:
                message = "missing IANA member"
                raise ValueError(message)
            data = stream.read()
            if hashlib.sha256(data).hexdigest() != digest:
                message = "IANA member digest mismatch"
                raise ValueError(message)
            for line in data.decode("utf-8").splitlines():
                fields = line.partition("#")[0].split()
                if fields and fields[0] in ("Zone", "Link"):
                    name = fields[1 if fields[0] == "Zone" else 2]
                    if not re.fullmatch(r"[A-Za-z0-9_+/-]+", name):
                        message = "unsupported IANA identifier"
                        raise ValueError(message)
                    names.add(name)
    if len(names) != source["name_count"]:
        message = "IANA name count mismatch"
        raise ValueError(message)
    header = (
        "// Generated by scripts/validation/generate_lti_time_zones.py; do not edit.\n"
        f"// IANA tzdata {source['version']}; archive SHA-256 {source['sha256']}.\n"
        "pub(super) const NAMES: &[&str] = &[\n"
    )
    return header + "".join(f'    "{name}",\n' for name in sorted(names)) + "];\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render()
    if args.check:
        if OUTPUT.read_text() != rendered:
            message = "generated IANA identifier table differs"
            raise ValueError(message)
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(rendered)


if __name__ == "__main__":
    main()
