#!/usr/bin/env python3
"""Effective-assumption graph for the production F* passes.

Subcommands:

``probe``    run the pinned verifier's own dependency analysis (``--dep full``) and a
             checked-file load probe (``--admit_smt_queries true --debug CheckedFiles``) for
             one pass, with the pass's own arguments, and record both outputs next to the pass
             records. The load probe runs the full type checker with SMT queries assumed; it
             is not verification evidence and is never admitted as such.
``build``    reconstruct the graph from the retained records, the recorded sources, the
             assumption register, the compliance matrix, the assurance contract and the
             Tamarin/Kani selections.
``check``    rebuild from the same fixed inputs and compare with a stored graph; reconcile the
             discovered premises with the register; exit 0 only when formally consistent.
``qualify``  additionally require accepted review status for every reachable premise and no
             open findings; exits 2 (incomplete) until that holds.

Formal consistency of the graph is not assurance. ``check`` never reports qualification and
``qualify`` never reports success on a mere schema or reconstruction success.
"""

