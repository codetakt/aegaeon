def diff_bodies(stored: dict[str, Any], rebuilt: dict[str, Any]) -> list[str]:
    reasons: list[str] = []
    for key in (
        "schema_version",
        "contract",
        "passes",
        "admission_sha256",
        "register_sha256",
        "source_identity",
    ):
        if stored.get(key) != rebuilt.get(key):
            reasons.append(f"{key}: stored {stored.get(key)!r} vs rebuilt {rebuilt.get(key)!r}")
    stored_nodes, rebuilt_nodes = stored.get("nodes", {}), rebuilt.get("nodes", {})
    for node_id in sorted(set(stored_nodes) - set(rebuilt_nodes)):
        reasons.append(f"node only in stored graph: {node_id}")
    for node_id in sorted(set(rebuilt_nodes) - set(stored_nodes)):
        reasons.append(f"node only in reconstruction: {node_id}")
    for node_id in sorted(set(stored_nodes) & set(rebuilt_nodes)):
        if stored_nodes[node_id] != rebuilt_nodes[node_id]:
            reasons.append(f"node attributes differ: {node_id}")

    def keys(edges: list[dict[str, Any]]) -> dict[tuple[str, str, str], dict[str, Any]]:
        result = {}
        for edge in edges:
            key = (edge["kind"], edge["from"], edge["to"])
            if key in result:
                reasons.append(f"duplicate edge: {' '.join(key)}")
            result[key] = edge
        return result

    stored_edges, rebuilt_edges = keys(stored.get("edges", [])), keys(rebuilt.get("edges", []))
    for edge_key in sorted(set(stored_edges) - set(rebuilt_edges)):
        reasons.append(f"edge only in stored graph: {' '.join(edge_key)}")
    for edge_key in sorted(set(rebuilt_edges) - set(stored_edges)):
        reasons.append(f"edge only in reconstruction: {' '.join(edge_key)}")
    for edge_key in sorted(set(stored_edges) & set(rebuilt_edges)):
        if stored_edges[edge_key] != rebuilt_edges[edge_key]:
            reasons.append(f"edge attributes differ: {' '.join(edge_key)}")
    if stored.get("findings") != rebuilt.get("findings"):
        reasons.append("findings differ between stored graph and reconstruction")
    return reasons


def reconcile_tool_premise(
    node_id: str, node: dict[str, Any], entries: list[dict[str, Any]], body: dict[str, Any]
) -> list[str]:
    """The observed node determines tool obligations, not a register's claimed kind."""
    reasons: list[str] = []
    if not entries:
        return [f"unregistered tool premise {node_id}"]
    tool = node.get("tool")
    if tool not in ("fstar", "solver"):
        return [f"tool premise {node_id} names an unsupported tool"]
    for entry in {entry["id"]: entry for entry in entries}.values():
        if entry.get("kind") != "tool":
            reasons.append(f"tool premise {node_id} is covered by non-tool register {entry['id']}")
            continue
        for pass_id in body["passes"]:
            observed = body["nodes"][f"pass:{pass_id}"].get(
                "tool" if tool == "fstar" else "solver_effective"
            )
            if not observed or observed.get("sha256") != entry.get("tool_sha256"):
                reasons.append(f"pass {pass_id}: {node_id} differs from registered tool digest")
    return reasons


def reconcile_register(body: dict[str, Any], register: dict[str, Any]) -> list[str]:
    reasons: list[str] = []
    validate_register(register)
    entries = register.get("entries")
    if register.get("schema_version") != REGISTER_SCHEMA_VERSION or not isinstance(entries, list):
        return ["register has an unsupported schema version or no entries"]
    by_premise: dict[str, dict[str, Any]] = {}
    coverage: list[dict[str, Any]] = []
    for entry in entries:
        for premise_id in entry.get("premise_ids", []):
            if premise_id in by_premise:
                reasons.append(f"register lists {premise_id} twice")
            by_premise[premise_id] = entry
        for selector in entry.get("covers", []):
            coverage.append({"entry": entry, **selector})
    nodes = body.get("nodes", {})
    for node_id, node in sorted(nodes.items()):
        if node.get("kind") != "premise":
            continue
        kind = node.get("premise_kind")
        if kind == "tool":
            registrations = [by_premise[node_id]] if node_id in by_premise else []
            registrations.extend(c["entry"] for c in coverage if _covers(c, node))
            reasons.extend(reconcile_tool_premise(node_id, node, registrations, body))
        elif kind in DECLARATION_KINDS:
            entry = by_premise.get(node_id)
            if entry is None:
                reasons.append(f"unregistered premise {node_id} ({kind})")
            elif entry.get("statements", {}).get(node_id) != node.get("statement_sha256"):
                reasons.append(f"statement of {node_id} differs from the registered statement")
        elif kind in COVERED_KINDS:
            if node_id in by_premise:
                continue
            if not any(_covers(selector, node) for selector in coverage):
                reasons.append(f"uncovered {kind} premise {node_id} (origin {node.get('origin')})")
    for premise_id, entry in sorted(by_premise.items()):
        if entry["kind"] == "tool":
            if premise_id not in nodes or nodes[premise_id].get("premise_kind") != "tool":
                reasons.append(f"registered tool premise {premise_id} is absent or is not a tool")
                continue
        if entry.get("kind") not in ("foreign-contract", "builder-injected", "declaration"):
            continue
        expected = entry.get("expected_in_closure", True)
        if premise_id in nodes and not expected:
            reasons.append(
                f"registered premise {premise_id} is marked outside the passes but was discovered"
            )
        if premise_id not in nodes and expected:
            reasons.append(
                f"registered premise {premise_id} was not discovered in any pass closure"
            )
    return reasons


def _covers(selector: dict[str, Any], node: dict[str, Any]) -> bool:
    if selector.get("kind") != node.get("premise_kind"):
        return False
    if "origin" in selector and selector["origin"] != node.get("origin"):
        return False
    if (
        "modules" in selector
        and f"{node.get('module')}#{node.get('role')}" not in selector["modules"]
    ):
        return False
    if "stale" in selector and bool(node.get("stale_reason")) != bool(selector["stale"]):
        return False
    if "verified_elsewhere" in selector and bool(node.get("verified_elsewhere")) != bool(
        selector["verified_elsewhere"]
    ):
        return False
    return True


def check_records(inputs: Inputs, body: dict[str, Any]) -> list[str]:
    reasons: list[str] = []
    if inputs.admission.get("status") != "accepted":
        reasons.append("admission record is not accepted")
    for pass_id in inputs.pass_ids():
        directory = inputs.evidence / "invocations" / pass_id
        modules = load_object(directory / "modules.json")
        pass_inputs = load_object(directory / "inputs.json")
        if modules.get("status") != "accepted":
            reasons.append(f"pass {pass_id}: module admission is not accepted")
        requested = sorted(m["path"] for m in modules.get("requested", []))
        recorded = sorted(m["path"] for m in pass_inputs.get("modules", []))
        if requested != recorded:
            reasons.append(
                f"pass {pass_id}: admission requested list differs from the invocation record"
            )
        expected_digest = inputs.admission["passes"][pass_id].get("modules_sha256")
        if digest_file(directory / "modules.json") != expected_digest:
            reasons.append(f"pass {pass_id}: modules.json does not match the admission digest")
        node = body["nodes"].get(f"pass:{pass_id}")
        if node is None:
            reasons.append(f"pass {pass_id}: missing from the graph")
            continue
        if node.get("denied_options"):
            reasons.append(f"pass {pass_id}: denied options {node['denied_options']}")
    return reasons


def check_load_modes(body: dict[str, Any]) -> list[str]:
    reasons: list[str] = []
    for node_id, node in sorted(body["nodes"].items()):
        if node.get("kind") != "source" or node.get("shadowed"):
            continue
        for pass_id, mode in node.get("load_modes", {}).items():
            if mode.get("mode") == "unobserved":
                reasons.append(f"pass {pass_id}: unresolved load mode for {node_id}")
    return reasons


def structural_reasons(body: dict[str, Any]) -> list[str]:
    """Schema validation plus referential integrity of the stored graph."""
    reasons: list[str] = []
    schema = load_object(SCHEMA_PATH)
    validator = jsonschema.Draft202012Validator(schema)
    for error in sorted(validator.iter_errors({"body": body, **_WRAPPER_STUB}), key=str)[:20]:
        reasons.append(f"schema: {error.message[:200]}")
    nodes = body.get("nodes", {})
    if not isinstance(nodes, dict) or not nodes:
        reasons.append("graph has no nodes")
        return reasons
    for edge in body.get("edges", []):
        if edge.get("from") not in nodes or edge.get("to") not in nodes:
            reasons.append(
                f"edge {edge.get('kind')} {edge.get('from')} -> {edge.get('to')} "
                "references an unknown node"
            )
    keys = [(e.get("kind"), e.get("from"), e.get("to")) for e in body.get("edges", [])]
    if len(keys) != len(set(keys)):
        reasons.append("duplicate logical edge keys in graph")
    return reasons


_WRAPPER_STUB = {
    "body_sha256": "0" * 64,
    "created_at": "",
    "builder": {"path": "", "sha256": "0" * 64},
}


def check_declarations(body: dict[str, Any]) -> list[str]:
    reasons: list[str] = []
    imports: dict[str, set[str]] = defaultdict(set)
    for edge in body["edges"]:
        if edge["kind"] == "imports" and edge["to"] in body["nodes"]:
            imports[edge["from"]].add(body["nodes"][edge["to"]].get("module"))
    for node_id, node in sorted(body["nodes"].items()):
        if node.get("kind") != "source" or node.get("origin") not in CWD_ORIGINS:
            continue
        for declaration in node.get("declarations", []):
            module = declaration["module"]
            imported = imports.get(node_id, set())
            # ``open X`` may name a namespace prefix (``open LowStar``) rather than a module.
            if (
                module == node.get("module")
                or module in imported
                or any(name.startswith(module + ".") for name in imported if name)
            ):
                continue
            reasons.append(
                f"{node_id}: declared dependency {module} ({declaration['kind']}, line "
                f"{declaration['line']}) is absent from the tool's dependency output"
            )
    return reasons


def check_cycles(body: dict[str, Any]) -> list[str]:
    adjacency: dict[str, set[str]] = defaultdict(set)
    for edge in body["edges"]:
        if edge["kind"] in ("depends-on", "justified-by"):
            adjacency[edge["from"]].add(edge["to"])
    state: dict[str, int] = {}
    reasons: list[str] = []

    def visit(node: str, path: list[str]) -> None:
        state[node] = 1
        for nxt in sorted(adjacency.get(node, ())):
            if state.get(nxt) == 1:
                reasons.append(f"circular justification: {' -> '.join([*path, node, nxt])}")
            elif nxt not in state:
                visit(nxt, [*path, node])
        state[node] = 2

    for node in sorted(adjacency):
        if node not in state:
            visit(node, [])
    return reasons


def check_expectations(body: dict[str, Any], expect: dict[str, Any], inputs: Inputs) -> list[str]:
    reasons: list[str] = []
    if "tree" in expect and expect["tree"] != body.get("source_identity"):
        reasons.append(
            f"source identity {body.get('source_identity')!r} differs from expected "
            f"{expect['tree']!r}"
        )
    for pass_id, paths in expect.get("selection", {}).items():
        record = inputs.evidence / "invocations" / pass_id / "inputs.json"
        recorded = (
            [m["path"] for m in load_object(record).get("modules", [])]
            if record.is_file()
            else None
        )
        if recorded != paths:
            reasons.append(f"pass {pass_id}: selection differs from the expected selection")
    if (
        "tool_sha256" in expect
        and body["nodes"].get("tool:fstar", {}).get("sha256") != expect["tool_sha256"]
    ):
        reasons.append("verifier identity differs from the expected tool digest")
    if (
        "receiver_sha256" in expect
        and digest_file(Path(__file__).resolve()) != expect["receiver_sha256"]
    ):
        reasons.append("this checker's digest differs from the expected receiver identity")
    if (
        "admitter_sha256" in expect
        and inputs.admission.get("admitter", {}).get("sha256") != expect["admitter_sha256"]
    ):
        reasons.append("admitter identity differs from the expected receiver identity")
    for path, sha256 in expect.get("sources", {}).items():
        node = body["nodes"].get(f"source:{path}")
        if node is None or node.get("sha256") != sha256:
            reasons.append(f"expected source {path} with digest {sha256} is absent or differs")
    return reasons


def run_check(
    args: argparse.Namespace, validated: dict[str, Any] | None = None
) -> tuple[int, dict[str, Any]]:
    stored = load_object(args.graph)
    body = stored.get("body")
    reasons: list[str] = []
    if not isinstance(body, dict):
        return 1, {"status": "inconsistent", "reasons": ["graph has no body"]}
    if stored.get("body_sha256") != digest_text(canonical(body)):
        reasons.append("body digest does not match the stored body")
    if body.get("schema_version") != SCHEMA_VERSION or body.get("contract") != CONTRACT:
        reasons.append("graph schema version or contract is unsupported")
    reasons.extend(structural_reasons(body))
    if reasons:
        return 1, {
            "mode": "check",
            "status": "inconsistent",
            "reasons": reasons,
            "note": "structural defects; reconstruction not compared",
        }
    inputs = Inputs(args.evidence, args.source_root, args.register)
    rebuilt = Builder(inputs, body.get("source_identity")).build()
    reasons.extend(diff_bodies(body, rebuilt))
    reasons.extend(reconcile_register(body, inputs.register))
    reasons.extend(check_records(inputs, body))
    reasons.extend(check_load_modes(body))
    reasons.extend(check_declarations(body))
    reasons.extend(check_cycles(body))
    if args.expect is not None:
        reasons.extend(check_expectations(body, load_object(args.expect), inputs))
    summary = {
        "mode": "check",
        "status": "consistent" if not reasons else "inconsistent",
        "reasons": reasons,
        "findings": body.get("findings", []),
        "nodes": len(body.get("nodes", {})),
        "edges": len(body.get("edges", [])),
        "note": "formal consistency only; not qualification",
    }
    if not reasons and validated is not None:
        validated.update(body=body, register=inputs.register)
    return (0 if not reasons else 1), summary


def run_qualify(args: argparse.Namespace) -> tuple[int, dict[str, Any]]:
    validated: dict[str, Any] = {}
    status, summary = run_check(args, validated)
    if status != 0:
        summary["mode"] = "qualify"
        summary["status"] = "inconsistent"
        return 1, summary
    body = validated["body"]
    register = validated["register"]
    entries = {e["id"]: e for e in register.get("entries", [])}
    blockers: list[str] = []
    for finding in body.get("findings", []):
        blockers.append(f"open finding {finding['code']}: {finding['message']}")
    registered: dict[str, dict[str, Any]] = {}
    coverage: list[dict[str, Any]] = []
    for entry in entries.values():
        for premise_id in entry.get("premise_ids", []):
            registered[premise_id] = entry
        for selector in entry.get("covers", []):
            coverage.append({"entry": entry, **selector})
        if entry.get("kind") in ("computational", "symbolic-abstraction"):
            registered[f"premise:{entry['id']}"] = entry
    cited = {e["to"] for e in body["edges"] if e["kind"] == "cites"}
    reachable: set[str] = set()
    for edge in body["edges"]:
        if edge["kind"] in ("depends-on", "tamarin-uses", "kani-uses") and edge["from"] in cited:
            reachable.add(edge["to"])
    for premise_id in sorted(reachable):
        node = body["nodes"][premise_id]
        if node.get("premise_kind") == "unknown-load":
            blockers.append(f"{premise_id}: absence of a load event does not establish non-use")
        entry = registered.get(premise_id)
        if entry is None:
            matches = [c["entry"] for c in coverage if _covers(c, node)]
            entry = matches[0] if matches else None
        if entry is None:
            blockers.append(
                f"{premise_id} is reachable from a cited property and has no register entry"
            )
        elif entry.get("status") != "accepted":
            blockers.append(
                f"{premise_id}: register status {entry.get('status')!r} is not accepted"
            )
    for premise_id in sorted(reachable):
        node = body["nodes"][premise_id]
        if node.get("premise_kind") == "tool" and any(
            f["code"].startswith("solver") for f in body.get("findings", [])
        ):
            blockers.append(f"{premise_id}: tool identity finding is open")
    summary = {
        "mode": "qualify",
        "status": "incomplete" if blockers else "qualified",
        "reasons": blockers,
        "reachable_premises": len(reachable),
        "cited_properties": len(cited),
    }
    return (2 if blockers else 0), summary


# --- CLI ---------------------------------------------------------------------------------------


def emit(summary: dict[str, Any]) -> None:
    print(f"ASSUMPTION-GRAPH {json.dumps(summary, sort_keys=True)}")
    for reason in summary.get("reasons", []):
        print(f"  - {reason}")


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    commands = parser.add_subparsers(dest="command", required=True)
    probe = commands.add_parser("probe", help="record dependency and load-mode probes for one pass")
    probe.add_argument("--out-dir", type=Path, required=True)
    probe.add_argument("--pass-id", required=True)
    probe.add_argument("argv", nargs=argparse.REMAINDER)
    for name in ("build", "check", "qualify"):
        sub = commands.add_parser(name)
        sub.add_argument("--evidence", type=Path, required=True)
        sub.add_argument("--source-root", type=Path, required=True)
        sub.add_argument("--register", type=Path, default=None)
        if name == "build":
            sub.add_argument("--out", type=Path, required=True)
            sub.add_argument("--source-identity", default=None)
        else:
            sub.add_argument("--graph", type=Path, required=True)
            sub.add_argument("--expect", type=Path, default=None)
    args = parser.parse_args()
    try:
        if args.command == "probe":
            argv: list[str] = args.argv
            if argv[:1] == ["--"]:
                argv = argv[1:]
            if not argv or not args.pass_id.replace("-", "").isalnum():
                parser.error("an argv and an alphanumeric/hyphen pass id are required")
            return run_probe(args.out_dir.resolve(), args.pass_id, argv)
        if args.register is None:
            args.register = args.source_root / "spec/assumption-register.json"
        if args.command == "build":
            body = build_graph(args.evidence, args.source_root, args.register, args.source_identity)
            args.out.write_text(canonical(wrap(body)))
            emit(
                {
                    "mode": "build",
                    "status": "built",
                    "nodes": len(body["nodes"]),
                    "edges": len(body["edges"]),
                    "findings": body["findings"],
                    "out": str(args.out),
                }
            )
            return 0
        status, summary = run_check(args) if args.command == "check" else run_qualify(args)
        emit(summary)
        return status
    except GraphError as error:
        emit({"mode": args.command, "status": "error", "reasons": [str(error)]})
        return 3 if args.command in ("probe", "build") else 1
    except OSError as error:
        emit({"mode": args.command, "status": "error", "reasons": [f"I/O error: {error}"]})
        return 3


if __name__ == "__main__":
    sys.exit(main())
