class GraphError(ValueError):
    """A fixed input is missing, malformed or contradicts another fixed input."""


# --- JSON, digests and paths ----------------------------------------------------------------


def _reject_duplicates(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise GraphError(f"duplicate JSON key {key!r}")
        result[key] = value
    return result


def _reject_constant(name: str) -> Any:
    raise GraphError(f"non-finite JSON number {name!r}")


def load_json(path: Path) -> Any:
    try:
        return json.loads(
            path.read_text(), object_pairs_hook=_reject_duplicates, parse_constant=_reject_constant
        )
    except (OSError, ValueError) as error:
        raise GraphError(f"cannot load {path}: {error}") from error


def load_object(path: Path) -> dict[str, Any]:
    value = load_json(path)
    if not isinstance(value, dict):
        raise GraphError(f"{path} is not a JSON object")
    return value


# The pinned Python shell has PyYAML at runtime but no loader type stubs.
class UniqueKeyLoader(yaml.SafeLoader):  # type: ignore[misc]
    """Reject overwritten evidence at every YAML mapping depth, including merges."""

    def flatten_mapping(self, node: yaml.MappingNode) -> None:
        # flatten_mapping removes merge markers, even empty or disjoint merges.
        # Check here so the parent's recursive calls also validate inline sources.
        if sum(key.tag == "tag:yaml.org,2002:merge" for key, _ in node.value) > 1:
            raise GraphError("duplicate YAML key '<<'")
        super().flatten_mapping(node)

    def construct_mapping(self, node: yaml.MappingNode, deep: bool = False) -> dict[Any, Any]:
        self.flatten_mapping(node)
        result: dict[Any, Any] = {}
        for key_node, value_node in node.value:
            key = self.construct_object(key_node, deep=deep)
            try:
                if key in result:
                    raise GraphError(f"duplicate YAML key {key!r}")
                result[key] = self.construct_object(value_node, deep=deep)
            except TypeError as error:
                raise GraphError("unhashable YAML mapping key") from error
        return result


def canonical(value: Any) -> str:
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def digest_text(text: str) -> str:
    return hashlib.sha256(text.encode()).hexdigest()


def digest_file(path: Path) -> str:
    with path.open("rb") as source:
        return hashlib.file_digest(source, "sha256").hexdigest()


def file_identity(path: Path) -> dict[str, str]:
    return {"path": str(path), "sha256": digest_file(path)}


def review_subject_digest(entry: dict[str, Any]) -> str:
    """Bind acceptance to the exact premise, independently of its review/status fields."""
    return digest_text(canonical({k: v for k, v in entry.items() if k not in {"review", "status"}}))


def validate_register(register: dict[str, Any]) -> None:
    validator = jsonschema.Draft202012Validator(
        load_object(REGISTER_SCHEMA_PATH), format_checker=jsonschema.FormatChecker()
    )
    errors = sorted(validator.iter_errors(register), key=str)
    if errors:
        raise GraphError("register schema: " + "; ".join(e.message[:200] for e in errors[:10]))
    ids: set[str] = set()
    for entry in register["entries"]:
        if entry["id"] in ids:
            raise GraphError(f"duplicate register entry {entry['id']}")
        ids.add(entry["id"])
        if entry["status"] == "accepted" and entry["review"][
            "subject_sha256"
        ] != review_subject_digest(entry):
            raise GraphError(f"register {entry['id']}: review belongs to a different premise")


def normalize_path(cwd: str, value: str) -> str:
    """Resolve a recorded path (absolute or cwd-relative) to its recorded absolute form."""
    if value.startswith("/"):
        return os.path.normpath(value)
    return os.path.normpath(os.path.join(cwd, value))


def rebase(value: str, old_root: str, new_root: str) -> str:
    prefix = old_root.rstrip("/") + "/"
    if value.startswith(prefix):
        return new_root.rstrip("/") + "/" + value[len(prefix) :]
    return value


def within(root: Path, candidate: Path) -> bool:
    try:
        candidate.resolve().relative_to(root.resolve())
    except ValueError:
        return False
    return True


# --- probe -----------------------------------------------------------------------------------


def strip_probe_options(argv: list[str]) -> list[str]:
    """Drop hint and diagnostic options; keep includes, warn_error flags and the sources."""
    kept: list[str] = []
    skip = False
    for value in argv:
        if skip:
            skip = False
            continue
        if value in PROBE_STRIP_FLAGS:
            continue
        if value in PROBE_STRIP_OPTIONS or value == "--debug":
            skip = True
            continue
        kept.append(value)
    return kept


def _capture(argv: list[str], stdout: Path, stderr: Path) -> int:
    with stdout.open("wb") as out, stderr.open("wb") as err:
        completed = subprocess.run(argv, stdout=out, stderr=err, check=False)
    return completed.returncode


def run_probe(out_dir: Path, pass_id: str, command: list[str]) -> int:
    tool = shutil.which(command[0])
    if tool is None:
        raise GraphError(f"verifier not found: {command[0]}")
    tool_path = Path(tool).absolute()
    directory = out_dir / "dependencies" / pass_id
    directory.mkdir(parents=True, exist_ok=False)
    rest = strip_probe_options(command[1:])
    dependency_argv = [str(tool_path), "--dep", "full", *rest]
    traced = command[1 : 1 + len(TRACE_OPTIONS)] == TRACE_OPTIONS
    diagnostics = TRACE_OPTIONS if traced else ["--debug", "CheckedFiles"]
    load_argv = [str(tool_path), "--admit_smt_queries", "true", *diagnostics, *rest]
    record: dict[str, Any] = {
        "schema_version": 1,
        "contract": DEP_CONTRACT,
        "load_contract": TRACE_CONTRACT if traced else LOAD_CONTRACT,
        "pass_id": pass_id,
        "cwd": str(Path.cwd()),
        "tool": file_identity(tool_path),
        "verifier_argv": command,
        "dependency_argv": dependency_argv,
        "load_argv": load_argv,
        "status": "incomplete",
    }
    (directory / "record.json").write_text(canonical(record))
    dep_rc = _capture(dependency_argv, directory / "depend.txt", directory / "depend.stderr")
    load_rc = _capture(load_argv, directory / "load.log", directory / "load.stderr")
    record.update(
        dependency_returncode=dep_rc,
        load_returncode=load_rc,
        dependency_sha256=digest_file(directory / "depend.txt"),
        load_sha256=digest_file(directory / "load.log"),
        status="succeeded" if dep_rc == 0 and load_rc == 0 else "failed",
    )
    (directory / "record.json").write_text(canonical(record))
    print(f"ASSUMPTION-GRAPH {json.dumps({'event': 'probe', **record}, sort_keys=True)}")
    return 0 if record["status"] == "succeeded" else 1


# --- F* source parsing -----------------------------------------------------------------------


def declaration_lines(lines: list[str], start: int) -> list[str]:
    """Return the declaration starting at ``start`` up to the next column-0 line."""
    block = [lines[start]]
    for line in lines[start + 1 :]:
        if line.strip() and not line[0].isspace():
            break
        block.append(line)
    return block


def normalize_statement(block: list[str]) -> str:
    words = " ".join(line.strip() for line in block if line.strip()).split()
    return " ".join(words)


def option_premises(stripped: str, masked: str) -> list[dict[str, Any]]:
    """Read real directive arguments without approximating F* escape decoding.

    F* decodes escapes before interpreting options. Until that decoding has a
    reviewed implementation here, escaped directive strings reject graph
    construction. Ordinary literals remain supported by the lexical scanner.
    """
    premises: list[dict[str, Any]] = []
    for directive in OPTION_DIRECTIVE.finditer(masked):
        tail = stripped[directive.end() :].lstrip()
        if not tail.startswith('"'):
            if directive.group() == "#set-options":
                raise GraphError("set-options directive has no supported string argument")
            # push/reset may save/reset the existing options without arguments.
            continue
        literal = re.match(r'"([^"\\]*)"', tail, re.DOTALL)
        if literal is None:
            raise GraphError("escaped option directives require explicit semantic review")
        if not WEAKENING_OPTION.search(literal[1]):
            continue
        number = stripped.count("\n", 0, directive.start()) + 1
        premises.append(
            {
                "kind": "lax-option",
                "name": f"option@{number}",
                "line": number,
                "statement": normalize_statement([directive.group() + " " + literal[0]]),
            }
        )
    return premises


def parse_fstar_source(text: str) -> dict[str, Any]:
    """Extract syntax sites outside comments and literals, retaining statements."""
    stripped, masked = admission.source_views(text)
    lines = stripped.splitlines()
    imports: list[dict[str, str]] = []
    premises = option_premises(stripped, masked)
    for number, line in enumerate(masked.splitlines(), 1):
        if match := OPEN_DECL.match(line):
            imports.append({"kind": match.group(1), "module": match.group(2), "line": str(number)})
            if match.group(1) == "friend":
                premises.append(
                    {
                        "kind": "friend-exposure",
                        "name": f"friend:{match.group(2)}",
                        "line": number,
                        "statement": normalize_statement([line]),
                    }
                )
            continue
        if match := ALIAS_DECL.match(line):
            imports.append({"kind": "alias", "module": match.group(1), "line": str(number)})
            continue
        if match := ASSUME_VAL.match(line):
            block = declaration_lines(lines, number - 1)
            premises.append(
                {
                    "kind": "assume-val",
                    "name": match.group(1),
                    "line": number,
                    "statement": normalize_statement(block),
                }
            )
            continue
        if ADMIT_CALL.search(line):
            premises.append(
                {
                    "kind": "admit",
                    "name": f"admit@{number}",
                    "line": number,
                    "statement": normalize_statement([lines[number - 1]]),
                }
            )
        elif ASSUME_TERM.search(line):
            premises.append(
                {
                    "kind": "assume-term",
                    "name": f"assume@{number}",
                    "line": number,
                    "statement": normalize_statement([lines[number - 1]]),
                }
            )
    return {
        "imports": imports,
        "premises": sorted(premises, key=lambda p: p["line"]),
        "text": stripped,
    }


def declares_symbol(text: str, name: str) -> bool:
    pattern = re.compile(
        r"(?m)^\s*(?:\[@@[^\]]*\]\s*)?(?:(?:private|unfold|irreducible|inline_for_extraction|"
        r"noextract|logic|total|noeq|unopteq|abstract|assume)\s+)*(?:let(?:\s+rec)?|val|type|and|"
        r"assume\s+val)\s+(?:#\w+\s+)?" + re.escape(name) + r"\b"
    )
    return pattern.search(admission.source_views(text)[1]) is not None


def regenerate_loops(driver_text: str) -> str:
    """Reproduce the builder-generated C.Loops.fst from the driver's printf block."""
    match = LOOPS_BLOCK.search(driver_text)
    if match is None:
        raise GraphError("driver has no C.Loops.fst generator block")
    lines: list[str] = []
    for raw in match.group(1).splitlines():
        value = raw.strip().rstrip("\\").strip()
        if not value:
            continue
        if not (value.startswith('"') and value.endswith('"')):
            raise GraphError(f"unexpected generator line {raw!r}")
        lines.append(value[1:-1])
    return "\n".join(lines) + "\n"


# --- dependency and load-log parsing -----------------------------------------------------------


def parse_depend(text: str) -> tuple[dict[str, list[str]], str | None]:
    """Parse ``fstar --dep full`` output into ``target -> [source, dep.checked, …]``."""
    entries: dict[str, list[str]] = {}
    version: str | None = None
    current: str | None = None
    for line in text.splitlines():
        if line.startswith("#"):
            if match := DEP_HEADER.match(line):
                version = match.group(1)
            continue
        if not line.strip():
            continue
        if line.startswith("\t"):
            if current is not None:
                entries[current].extend(x for x in line.strip().split() if x != "\\")
            continue
        head, separator, tail = line.partition(":")
        if not separator or "=" in head:
            current = None
            continue
        current = head.strip()
        if current in entries:
            raise GraphError(f"duplicate dependency target {current}")
        entries[current] = [x for x in tail.split() if x != "\\"]
    if not entries:
        raise GraphError("dependency output has no targets")
    return entries, version


def parse_load_log(text: str) -> dict[str, Any]:
    attempted: set[str] = set()
    tc_attempted: set[str] = set()
    loaded: set[str] = set()
    stale: dict[str, str] = {}
    lax: dict[str, str] = {}
    verified: dict[str, str] = {}
    loaded_lines: dict[str, int] = {}
    verified_lines: dict[str, int] = {}
    for number, line in enumerate(text.splitlines(), 1):
        if match := TRYING.match(line):
            attempted.add(match.group(1).strip())
            if TRYING_TC.match(line):
                tc_attempted.add(match.group(1).strip())
        elif match := LOADED.match(line):
            loaded.add(match.group(1).strip())
            loaded_lines[match.group(1).strip()] = number
        elif match := STALE.match(line):
            stale[match.group(1).strip()] = match.group(2).strip()
        elif match := LAX.match(line):
            lax[f"{match.group(2)}#{match.group(1)}"] = line
        elif match := VERIFYING.match(line):
            verified[f"{match.group(2)}#{match.group(1)}"] = line
            verified_lines[f"{match.group(2)}#{match.group(1)}"] = number
        elif line.startswith(
            (
                "Trying to load checked",
                "Successfully loaded module",
                "Checked file ",
                "Now lax-checking",
                "Now verifying",
            )
        ):
            raise GraphError(f"malformed load-mode record: {line[:200]}")
    if not attempted:
        raise GraphError("load-mode evidence missing (no checked-file load attempts recorded)")
    return {
        "attempted": attempted,
        "tc_attempted": tc_attempted,
        "loaded": loaded,
        "stale": stale,
        "lax": lax,
        "verified": verified,
        "loaded_lines": loaded_lines,
        "verified_lines": verified_lines,
    }


def parse_batch_schedule(text: str, cwd: str) -> dict[str, list[str]]:
    """Read the pinned batch driver's complete ordered work lists, once each.

    A schedule is not a completion record. Its members must separately have an
    admitted result or a positive load/check event. In particular, adjacent
    interface/implementation pairs are interleaved by Universal.tc_fold_interleave.
    """
    schedules: dict[str, list[str]] = {}
    for line in text.splitlines():
        for prefix, name in ((PROCESS_FILES, "process"), (VERIFY_FILES, "verify")):
            if not line.startswith(prefix):
                if line.startswith(prefix.rstrip()):
                    raise GraphError("malformed batch schedule")
                continue
            if name in schedules:
                raise GraphError(f"duplicate batch {name} schedule")
            paths = line.removeprefix(prefix).split()
            if not paths or any(not p.endswith((".fst", ".fsti")) for p in paths):
                raise GraphError(f"empty or malformed batch {name} schedule")
            paths = [normalize_path(cwd, p) for p in paths]
            if len(paths) != len(set(paths)):
                raise GraphError(f"duplicate path in batch {name} schedule")
            schedules[name] = paths
    if set(schedules) != {"process", "verify"}:
        raise GraphError("missing complete batch schedule")
    if not set(schedules["verify"]) <= set(schedules["process"]):
        raise GraphError("batch verify schedule is outside process schedule")
    return schedules


def normalize_load_paths(load: dict[str, Any], cwd: str) -> dict[str, Any]:
    loaded_lines: dict[str, int] = {}
    for path, number in load["loaded_lines"].items():
        normalized = normalize_path(cwd, path)
        loaded_lines[normalized] = max(loaded_lines.get(normalized, 0), number)
    return {
        **load,
        "attempted": {normalize_path(cwd, p) for p in load["attempted"]},
        "tc_attempted": {normalize_path(cwd, p) for p in load["tc_attempted"]},
        "loaded": {normalize_path(cwd, p) for p in load["loaded"]},
        "stale": {normalize_path(cwd, p): v for p, v in load["stale"].items()},
        "loaded_lines": loaded_lines,
    }


def traced_load_modes(
    schedule: dict[str, list[str]],
    load: dict[str, Any],
    targets: dict[str, str],
    requested: set[str],
) -> dict[str, dict[str, str]]:
    """Resolve positive batch evidence without dropping conservative dependencies."""
    scheduled = set(schedule["process"])
    sources = set(targets.values())
    if not scheduled <= sources:
        raise GraphError("batch schedule includes a source absent from dependency output")
    roles = {f"{Path(p).name.rsplit('.', 1)[0]}#{admission.source_role(p)}" for p in sources}
    if len(roles) != len(sources):
        raise GraphError("ambiguous module/role in batch dependency sources")
    if not (set(load["lax"]) | set(load["verified"])) <= roles:
        raise GraphError("source-check event absent from dependency output")
    if not load["loaded"] <= set(targets):
        raise GraphError("checked load event absent from dependency output")
    if not load["tc_attempted"] <= set(targets):
        raise GraphError("type-checker load attempt absent from dependency output")
    if not requested <= set(schedule["verify"]):
        raise GraphError("requested source absent from batch verification schedule")
    requested_modules = {Path(p).name.rsplit(".", 1)[0].lower() for p in requested}
    expected_verify = [
        p
        for p in schedule["process"]
        if Path(p).name.rsplit(".", 1)[0].lower() in requested_modules
    ]
    if schedule["verify"] != expected_verify:
        raise GraphError("batch verification schedule differs from requested module selection")
    pairs = {
        interface: implementation
        for interface, implementation in zip(
            schedule["process"], schedule["process"][1:], strict=False
        )
        if interface.endswith(".fsti")
        and implementation.endswith(".fst")
        and Path(interface).name[:-1].lower() == Path(implementation).name.lower()
    }
    modes: dict[str, dict[str, str]] = {}
    for checked, source in targets.items():
        module = Path(source).name.rsplit(".", 1)[0]
        key = f"{module}#{admission.source_role(source)}"
        if key in load["lax"] and key in load["verified"]:
            raise GraphError(f"contradictory source-check events: {source}")
        # A cache may be successfully read and then ignored (e.g. --force).
        # Prefer the subsequent source check to the artifact read.
        mode = (
            "lax-source"
            if key in load["lax"]
            else "verified-dependency"
            if key in load["verified"]
            else "checked-artifact"
            if checked in load["loaded"]
            else None
        )
        if mode is not None:
            if source not in scheduled and not (
                source.endswith(".fsti") and source[:-1] in scheduled
            ):
                raise GraphError(f"load/check event outside batch schedule: {source}")
            modes[source] = {"mode": mode}
    for source, implementation in pairs.items():
        if (
            source not in modes or modes[source]["mode"] == "checked-artifact"
        ) and implementation in modes:
            impl_mode = modes[implementation]["mode"]
            if impl_mode in ("lax-source", "verified-dependency"):
                # An interface cache can be read only for dependency bookkeeping.
                # When its paired implementation falls back to source, pre_fn
                # interleaving checks the interface from source as well.
                modes[source] = {"mode": impl_mode, "interleaved_with": implementation}
    for checked, source in targets.items():
        if source in scheduled and source not in modes:
            raise GraphError(f"scheduled source has no positive load/check event: {source}")
        if (
            source in modes
            and source in set(schedule["verify"])
            and modes[source]["mode"] == "lax-source"
        ):
            raise GraphError(f"verification-scheduled source was lax-checked: {source}")
        if (
            source in modes
            and source in set(schedule["verify"])
            and modes[source]["mode"] == "checked-artifact"
        ):
            raise GraphError(
                f"verification-scheduled source only reused a checked artifact: {source}"
            )
        if (
            source in modes
            and source not in set(schedule["verify"])
            and modes[source]["mode"] == "verified-dependency"
        ):
            raise GraphError(f"source verification event outside verification schedule: {source}")
        if checked in load["tc_attempted"] and source not in modes:
            raise GraphError(f"unresolved type-checker load attempt: {source}")
        if source not in modes and checked in load["attempted"]:
            # Positive full dependency membership + a complete batch schedule + a
            # parsing-cache attempt. This does not establish irrelevance or soundness.
            modes[source] = {"mode": "dependency-scan"}
    return modes


def effective_solver(output_text: str, tool_path: Path) -> dict[str, Any]:
    """Resolve every solver start; mixed or malformed restart evidence is rejected."""
    matches = [match for line in output_text.splitlines() if (match := Z3PROC.fullmatch(line))]
    if output_text.count("Creating new z3proc") != len(matches):
        raise GraphError("malformed solver process record")
    if not matches:
        return {"observed": False, "name": None, "version": None, "path": None, "sha256": None}
    identities = [_solver_process(match.group(1), match.group(2), tool_path) for match in matches]
    first = identities[0]

    # Names may be aliases of the same executable, but both observed version and
    # resolved bytes must agree. Unknown paths cannot conceal a different name.
    def identity(value: dict[str, Any]) -> tuple[Any, ...]:
        return (value["path"] or value["name"], value["sha256"], value["version"])

    if any(identity(value) != identity(first) for value in identities[1:]):
        raise GraphError("mixed solver process identities in one invocation")
    return {**first, "arguments": ["-smt2", "-in"], "process_count": len(identities)}


def _solver_process(name: str, version: str, tool_path: Path) -> dict[str, Any]:
    directories: list[str] = []
    try:
        for line in tool_path.read_text(errors="replace").splitlines():
            if prepend := PATH_PREPEND.match(line):
                directories.append(prepend.group(1))
    except (OSError, UnicodeError):
        pass
    directories.extend(os.environ.get("PATH", "").split(os.pathsep))
    for directory in directories:
        candidate = Path(directory) / name
        if candidate.is_file() and os.access(candidate, os.X_OK):
            return {
                "observed": True,
                "name": name,
                "version": version,
                "path": str(candidate.resolve()),
                "sha256": digest_file(candidate),
            }
    return {"observed": True, "name": name, "version": version, "path": None, "sha256": None}


# --- Tamarin and Kani premise indexes ----------------------------------------------------------


def tamarin_selection(script_text: str) -> dict[str, list[str]]:
    """Parse the ``PROOFS=( … )`` array; continuation strings without ``:`` join the entry."""
    match = re.search(r"PROOFS=\((.*?)\n\)", script_text, re.DOTALL)
    if match is None:
        raise GraphError("Tamarin selection array not found")
    parts = re.findall(r'"([^"]*)"', match.group(1))
    specs: list[str] = []
    for part in parts:
        if ":" in part:
            specs.append(part)
        elif specs:
            specs[-1] += part
        else:
            raise GraphError(f"selection continuation without a theory: {part!r}")
    selection: dict[str, list[str]] = {}
    for spec in specs:
        theory, _, lemmas = spec.partition(":")
        if theory in selection:
            raise GraphError(f"duplicate Tamarin theory selection {theory}")
        selection[theory] = [lemma for lemma in lemmas.split(",") if lemma]
    return selection


def parse_theory(text: str) -> dict[str, Any]:
    lemmas: list[str] = []
    restrictions: list[str] = []
    headers: dict[str, list[str]] = {"builtins": [], "functions": [], "equations": []}
    lines = text.splitlines()
    index = 0
    while index < len(lines):
        line = lines[index]
        if match := TAMARIN_LEMMA.match(line):
            lemmas.append(match.group(1))
        elif match := TAMARIN_RESTRICTION.match(line):
            restrictions.append(match.group(1))
        elif match := TAMARIN_HEADER.match(line):
            body = match.group(2).strip()
            while not body.endswith(("]", ";")) and index + 1 < len(lines):
                nxt = lines[index + 1].strip()
                if not nxt or nxt.startswith(
                    (
                        "lemma",
                        "rule",
                        "restriction",
                        "axiom",
                        "builtins",
                        "functions",
                        "equations",
                        "heuristic",
                        "/*",
                        "//",
                        "end",
                    )
                ):
                    break
                index += 1
                body = f"{body} {nxt}".strip()
            headers[match.group(1)].extend(
                item.strip() for item in body.rstrip(";").split(",") if item.strip()
            )
        index += 1
    return {"lemmas": lemmas, "restrictions": restrictions, **headers}


# --- graph construction ----------------------------------------------------------------------


class Graph:
    """Accumulates nodes and edges with deterministic ordering."""

    def __init__(self) -> None:
        self.nodes: dict[str, dict[str, Any]] = {}
        self.edges: dict[tuple[str, str, str], dict[str, Any]] = {}
        self.findings: list[dict[str, Any]] = []

    def node(self, node_id: str, kind: str, **attrs: Any) -> dict[str, Any]:
        existing = self.nodes.get(node_id)
        if existing is None:
            existing = {"kind": kind, **attrs}
            self.nodes[node_id] = existing
        elif existing["kind"] != kind:
            raise GraphError(f"node {node_id} declared as {existing['kind']} and {kind}")
        else:
            existing.update(attrs)
        return existing

    def edge(self, kind: str, source: str, target: str, **attrs: Any) -> dict[str, Any]:
        key = (kind, source, target)
        existing = self.edges.get(key)
        if existing is None:
            existing = {"kind": kind, "from": source, "to": target, **attrs}
            self.edges[key] = existing
        else:
            for name, value in attrs.items():
                if name in ("passes", "evidence", "events"):
                    existing[name] = sorted(set(existing.get(name, [])) | set(value))
                else:
                    existing[name] = value
        return existing

    def finding(self, code: str, message: str, **attrs: Any) -> None:
        self.findings.append({"code": code, "message": message, **attrs})

    def body(self, meta: dict[str, Any]) -> dict[str, Any]:
        for node_id in self.nodes:
            if not node_id or "\n" in node_id:
                raise GraphError(f"invalid node id {node_id!r}")
        for kind, source, target in self.edges:
            if source not in self.nodes or target not in self.nodes:
                raise GraphError(f"edge {kind} {source} -> {target} references an unknown node")
        return {
            **meta,
            "nodes": dict(sorted(self.nodes.items())),
            "edges": [self.edges[key] for key in sorted(self.edges)],
            "findings": sorted(self.findings, key=lambda f: json.dumps(f, sort_keys=True)),
        }


class Inputs:
    """Fixed inputs of a build, resolved against the local checkout."""

    def __init__(self, evidence: Path, source_root: Path, register: Path) -> None:
        self.evidence = evidence.resolve()
        self.source_root = source_root.resolve()
        self.register_path = register
        if not (self.evidence / "admission.json").is_file():
            raise GraphError(f"admission record missing under {self.evidence}")
        self.admission = load_object(self.evidence / "admission.json")
        self.register = load_object(register)
        validate_register(self.register)
        # Reuse the admission verifier rather than trusting its old status strings.
        # This validates proof inputs, output and dispositions before any graph is built.
        try:
            admission.verify_records(self.evidence, self.pass_ids())
        except (admission.AdmissionError, KeyError, TypeError, ValueError) as error:
            raise GraphError(f"proof admission replay: {error}") from error
        self.matrix = self._load_yaml(self.source_root / "spec/compliance-matrix.yaml")
        self.contract = load_object(self.source_root / "spec/server-assurance-contract.v1.json")
        self.driver = self.source_root / "scripts/flake/verify_fstar.sh"
        self.tamarin_script = self.source_root / "ci/tamarin_proofs.sh"
        self.proofs_root = self.source_root / "proofs/tamarin"
        self.kani = load_object(self.source_root / "spec/kani-evidence.json")
        self.source_texts: dict[str, str] = {}

    @staticmethod
    def _load_yaml(path: Path) -> dict[str, Any]:
        try:
            value = yaml.load(path.read_text(), Loader=UniqueKeyLoader)
        except (OSError, yaml.YAMLError) as error:
            raise GraphError(f"cannot load {path}: {error}") from error
        if not isinstance(value, dict):
            raise GraphError(f"{path} is not a mapping")
        return value

    def pass_ids(self) -> list[str]:
        passes = self.admission.get("passes")
        if not isinstance(passes, dict) or not passes:
            raise GraphError("admission record lists no passes")
        return sorted(passes)

    def pass_records(self, pass_id: str) -> dict[str, Any]:
        directory = self.evidence / "invocations" / pass_id
        dependencies = self.evidence / "dependencies" / pass_id
        if not (dependencies / "record.json").is_file():
            raise GraphError(f"dependency record missing for pass {pass_id}")
        inputs = load_object(directory / "inputs.json")
        result = load_object(directory / "result.json")
        modules = load_object(directory / "modules.json")
        record = load_object(dependencies / "record.json")
        for name in ("depend.txt", "load.log"):
            if not (dependencies / name).is_file():
                raise GraphError(f"{name} missing for pass {pass_id}")
        traced = inputs["argv"][1 : 1 + len(TRACE_OPTIONS)] == TRACE_OPTIONS
        if (record.get("load_contract") == TRACE_CONTRACT) != traced:
            raise GraphError(f"pass {pass_id}: proof and probe trace contracts differ")
        if record.get("contract") != DEP_CONTRACT or record.get("load_contract") not in (
            LOAD_CONTRACT,
            TRACE_CONTRACT,
        ):
            raise GraphError(f"pass {pass_id}: dependency record has an unsupported contract")
        if record.get("pass_id") != pass_id:
            raise GraphError(
                f"pass {pass_id}: dependency record belongs to {record.get('pass_id')}"
            )
        if record.get("verifier_argv") != inputs.get("argv"):
            raise GraphError(f"pass {pass_id}: dependency probe argv differs from the pass argv")
        if record.get("tool", {}).get("sha256") != inputs.get("tool", {}).get("sha256"):
            raise GraphError(f"pass {pass_id}: dependency probe used a different verifier")
        tool = inputs.get("tool", {})
        if record.get("tool") != tool or digest_file(Path(tool["path"])) != tool.get("sha256"):
            raise GraphError(f"pass {pass_id}: probe verifier identity differs")
        rest = strip_probe_options(inputs["argv"][1:])
        if traced and inputs["argv"][1 : 1 + len(TRACE_OPTIONS)] != TRACE_OPTIONS:
            raise GraphError(f"pass {pass_id}: batch trace options absent from proof argv")
        expected_dep = [tool["path"], "--dep", "full", *rest]
        expected_load = [
            tool["path"],
            "--admit_smt_queries",
            "true",
            *(TRACE_OPTIONS if traced else ["--debug", "CheckedFiles"]),
            *rest,
        ]
        if (
            record.get("dependency_argv") != expected_dep
            or record.get("load_argv") != expected_load
        ):
            raise GraphError(
                f"pass {pass_id}: actual probe argv differs from the declared derivation"
            )
        if any(
            type(record.get(k)) is not int or record[k] != 0
            for k in ("dependency_returncode", "load_returncode")
        ):
            raise GraphError(f"pass {pass_id}: probe return code is not zero")
        admitted = self.admission["passes"][pass_id]
        for key in ("inputs_sha256", "output_sha256"):
            if admitted.get(key) != result.get(key):
                raise GraphError(f"pass {pass_id}: {key} differs from admission summary")
        for name, key in (("depend.txt", "dependency_sha256"), ("load.log", "load_sha256")):
            if digest_file(dependencies / name) != record.get(key):
                raise GraphError(f"pass {pass_id}: {name} does not match its record digest")
        if record.get("status") != "succeeded":
            raise GraphError(f"pass {pass_id}: dependency probe did not succeed")
        return {
            "inputs": inputs,
            "result": result,
            "modules": modules,
            "record": record,
            "depend": (dependencies / "depend.txt").read_text(errors="replace"),
            "load": (dependencies / "load.log").read_text(errors="replace"),
            "output": (directory / "output.log").read_text(errors="replace"),
        }


class Builder:
    """Reconstructs the graph from ``Inputs``."""

    def __init__(self, inputs: Inputs, source_identity: str | None) -> None:
        self.inputs = inputs
        self.graph = Graph()
        self.source_identity = source_identity
        self.recorded_root: str | None = None
        self.ulib_prefix: str | None = None
        self.providers: dict[str, str] = {}
        self.imports: dict[str, set[str]] = defaultdict(set)
        self.satisfied_by: dict[str, set[str]] = defaultdict(set)
        self.module_of: dict[str, str] = {}
        self.parsed: dict[str, dict[str, Any]] = {}
        self.pass_meta: dict[str, dict[str, Any]] = {}
        self.loops_origin: str | None = None
        self.declares_by_source: dict[str, list[str]] = defaultdict(list)
        self.interpretation_by_source: dict[str, set[str]] = defaultdict(set)
        self.batch_traces: dict[str, dict[str, Any]] = {}

    # -- origins and local resolution --

    def origin(self, recorded: str) -> str:
        for prefix, origin in self.providers.items():
            if recorded.startswith(prefix.rstrip("/") + "/"):
                return origin
        if self.ulib_prefix and recorded.startswith(self.ulib_prefix):
            return "ulib"
        root = self.recorded_root or ""
        if recorded == f"{root}/fstar/C.Loops.fst" and self.loops_origin == LOOPS_ORIGIN:
            return "builder-generated"
        if recorded.startswith(f"{root}/generated/everparse/"):
            return "generated-everparse"
        if recorded.startswith(f"{root}/tests/fstar/"):
            return "test"
        if recorded.startswith(f"{root}/fstar/"):
            return "first-party"
        return "unknown"

    def local(self, recorded: str) -> Path:
        """Map a recorded absolute path to the local checkout or the immutable provider path."""
        root = self.recorded_root or ""
        if recorded.startswith(root + "/"):
            candidate = self.inputs.source_root / recorded[len(root) + 1 :]
            if not within(self.inputs.source_root, candidate):
                raise GraphError(f"recorded path escapes the source root: {recorded}")
            return candidate
        return Path(recorded)

    # -- per-pass processing --

    def process_pass(self, pass_id: str) -> None:
        records = self.inputs.pass_records(pass_id)
        inputs = records["inputs"]
        cwd = inputs["cwd"]
        self.recorded_root = os.path.dirname(cwd)
        self.loops_origin = inputs.get("loops_origin")
        self.providers = {
            path: PROVIDER_ORIGINS[name]
            for name, path in inputs.get("providers", {}).items()
            if name in PROVIDER_ORIGINS and path
        }
        tool_path = Path(inputs["tool"]["path"])
        self.ulib_prefix = str(tool_path.parent.parent / "lib" / "fstar") + "/"
        probe_cwd = records["record"].get("cwd")
        entries, version = parse_depend(records["depend"])
        if isinstance(probe_cwd, str) and probe_cwd != cwd:
            # A replay from another directory reports include-resolved files under its own
            # working directory; rebase them onto the pass directory (recorded as a finding).
            entries = {
                rebase(target, probe_cwd, cwd): [rebase(d, probe_cwd, cwd) for d in deps]
                for target, deps in entries.items()
            }
        load = parse_load_log(records["load"])
        if isinstance(probe_cwd, str) and probe_cwd != cwd:
            load = {
                key: (
                    {rebase(p, probe_cwd, cwd): v for p, v in value.items()}
                    if isinstance(value, dict)
                    else {rebase(p, probe_cwd, cwd) for p in value}
                )
                for key, value in load.items()
            }
        load = normalize_load_paths(load, cwd)
        solver = effective_solver(records["output"], tool_path)
        requested = {
            normalize_path(cwd, entry["path"]): entry for entry in records["modules"]["requested"]
        }
        if records["record"]["load_contract"] == TRACE_CONTRACT:
            if probe_cwd != cwd:
                raise GraphError(f"pass {pass_id}: traced proof and probe directories differ")
            proof_schedule = parse_batch_schedule(records["output"], cwd)
            probe_schedule = parse_batch_schedule(records["load"], cwd)
            if proof_schedule != probe_schedule:
                raise GraphError(f"pass {pass_id}: proof and probe batch schedules differ")
            proof_load = normalize_load_paths(parse_load_log(records["output"]), cwd)
            load = normalize_load_paths(load, cwd)
            self.batch_traces[pass_id] = {
                "schedule": proof_schedule,
                "proof": proof_load,
                "probe": load,
            }
            load = proof_load
        identities = [*inputs.get("modules", []), *inputs.get("local_context", [])]
        identities.extend(
            {"path": m["source"], "sha256": m["sha256"]}
            for m in records["modules"].get("unrequested", [])
            if m.get("classification") == "dependency"
        )
        recorded_digests: dict[str, str] = {}
        for identity in identities:
            path = normalize_path(cwd, identity["path"])
            value = identity["sha256"]
            if not isinstance(value, str) or not re.fullmatch(r"[0-9a-f]{64}", value):
                raise GraphError(f"pass {pass_id}: malformed source identity for {path}")
            if path in recorded_digests and recorded_digests[path] != value:
                raise GraphError(f"pass {pass_id}: conflicting source identities for {path}")
            recorded_digests[path] = value
        denied = sorted(
            option
            for option in inputs["argv"]
            if option.partition("=")[0] in admission.DENIED_OPTIONS
        )
        self.graph.node(
            f"pass:{pass_id}",
            "pass",
            argv_sha256=digest_text(json.dumps(inputs["argv"])),
            cwd=cwd,
            include_paths=inputs.get("include_paths", []),
            tool=inputs["tool"],
            tool_version=version,
            solver_recorded=inputs.get("solver"),
            solver_effective=solver,
            denied_options=denied,
            admission_status=records["modules"].get("status"),
            records={
                "inputs_sha256": records["result"].get("inputs_sha256"),
                "output_sha256": records["result"].get("output_sha256"),
                "modules_sha256": self.inputs.admission["passes"][pass_id].get("modules_sha256"),
                "dependency_sha256": records["record"]["dependency_sha256"],
                "load_sha256": records["record"]["load_sha256"],
                "probe_record_sha256": digest_file(
                    self.inputs.evidence / "dependencies" / pass_id / "record.json"
                ),
                "result_sha256": digest_file(
                    self.inputs.evidence / "invocations" / pass_id / "result.json"
                ),
            },
            loops_origin=self.loops_origin,
        )
        self.pass_meta[pass_id] = {"cwd": cwd, "requested": requested}
        if pass_id in self.batch_traces:
            self.graph.nodes[f"pass:{pass_id}"]["batch_schedule"] = self.batch_traces[pass_id][
                "schedule"
            ]
            self.graph.nodes[f"pass:{pass_id}"]["load_evidence"] = "proof-output"
        self.graph.node("tool:fstar", "tool", path=str(tool_path), sha256=inputs["tool"]["sha256"])
        self.graph.node(
            "premise:tool:fstar",
            "premise",
            premise_kind="tool",
            tool="fstar",
            path=str(tool_path),
            sha256=inputs["tool"]["sha256"],
            version=version,
        )
        self.record_solver(pass_id, inputs.get("solver"), solver)
        if records["record"].get("cwd") != cwd:
            self.graph.finding(
                "probe-directory-differs",
                f"pass {pass_id}: the dependency probe ran in {records['record'].get('cwd')}, "
                f"the pass in {cwd}; relative paths were resolved against the pass directory",
                pass_id=pass_id,
            )
        self.record_closure(pass_id, cwd, entries, load, requested, recorded_digests)

    def record_solver(self, pass_id: str, recorded: Any, effective: dict[str, Any]) -> None:
        recorded_sha = recorded.get("sha256") if isinstance(recorded, dict) else None
        self.graph.node(
            "premise:tool:solver",
            "premise",
            premise_kind="tool",
            tool="solver",
            recorded=recorded,
            effective=effective,
        )
        if not effective["observed"]:
            self.graph.finding(
                "solver-unobserved",
                f"pass {pass_id}: no solver start line in the output",
                pass_id=pass_id,
            )
        elif effective["sha256"] is None:
            self.graph.finding(
                "solver-unresolved",
                f"pass {pass_id}: solver {effective['name']} could not be resolved to a file",
                pass_id=pass_id,
            )
        elif effective["sha256"] != recorded_sha:
            self.graph.finding(
                "solver-identity-mismatch",
                f"pass {pass_id}: records name solver {recorded_sha} but {effective['name']} "
                f"({effective['sha256']}) was started",
                pass_id=pass_id,
            )

    def record_closure(
        self,
        pass_id: str,
        cwd: str,
        entries: dict[str, list[str]],
        load: dict[str, Any],
        requested: dict[str, dict[str, Any]],
        recorded_digests: dict[str, str],
    ) -> None:
        checked_targets: dict[str, str] = {}
        checked_deps: dict[str, list[str]] = {}
        for target, deps in entries.items():
            if not target.endswith(".checked") or not deps:
                continue
            checked = normalize_path(cwd, target)
            checked_targets[checked] = normalize_path(cwd, deps[0])
            checked_deps[checked] = [normalize_path(cwd, dep) for dep in deps[1:]]
        traced_modes: dict[str, dict[str, str]] = {}
        if pass_id in self.batch_traces:
            trace = self.batch_traces[pass_id]
            traced_modes = traced_load_modes(
                trace["schedule"], trace["proof"], checked_targets, set(requested)
            )
            probe_modes = traced_load_modes(
                trace["schedule"], trace["probe"], checked_targets, set(requested)
            )
            if traced_modes != probe_modes:
                raise GraphError(f"pass {pass_id}: proof and probe load modes differ")
        for checked, source in checked_targets.items():
            role = admission.source_role(source)
            module = Path(source).name.removesuffix(".fsti").removesuffix(".fst")
            origin = self.origin(source)
            if origin == "unknown":
                raise GraphError(f"pass {pass_id}: {source} lies outside every recorded root")
            node_id = f"source:{source}"
            attrs: dict[str, Any] = {"module": module, "role": role, "origin": origin}
            digest = recorded_digests.get(source)
            if origin in CWD_ORIGINS:
                attrs["sha256"] = self.cwd_source_digest(pass_id, source, digest, origin)
            else:
                attrs["sha256"] = self.retained_dependency_digest(pass_id, source, digest)
            self.graph.node(node_id, "source", **attrs)
            self.module_of.setdefault(node_id, module)
            mode = self.load_mode(pass_id, source, checked, module, role, requested, load)
            if source in traced_modes:
                observed = traced_modes[source]
                if observed["mode"] == "dependency-scan" and origin in CWD_ORIGINS:
                    # First-party implementation obligations need their own proof;
                    # a parsing scan cannot discharge them.
                    pass
                else:
                    mode.update(observed)
                    mode["evidence"] = "proof-output"
                    if mode["mode"] == "dependency-scan":
                        mode["checked"] = "parsing-attempt"
                    if source in requested:
                        mode["mode"] = "requested-verified"
            node = self.graph.nodes[node_id]
            node.setdefault("load_modes", {})[pass_id] = mode
            if checked != source + ".checked" and self.same_named_source_exists(checked, source):
                # The verifier placed the artifact with another directory's copy of this
                # module (for example KaRaMeL's C.Loops.fst); a checked directory that holds
                # no source of that name (ulib.checked) is the tool's own layout, not a shadow.
                self.graph.edge(
                    "shadows",
                    node_id,
                    self.ensure_shadow_target(checked),
                    passes=[pass_id],
                    evidence=["checked target attributed to a different directory than the source"],
                )
            checked_attrs: dict[str, Any] = {"origin": self.origin(checked)}
            # A source recheck supersedes a discarded cache read. Bind bytes
            # whenever the admitted mode actually relies on the checked artifact.
            if mode["mode"] == "checked-artifact":
                checked_attrs["sha256"] = self.retained_dependency_digest(
                    pass_id, checked, recorded_digests.get(checked)
                )
            self.graph.node(
                f"checked:{checked}",
                "checked",
                **checked_attrs,
            ).setdefault("load_modes", {})[pass_id] = mode["checked"]
            self.graph.edge("loads", f"pass:{pass_id}", f"checked:{checked}", passes=[pass_id])
            if source in requested:
                self.graph.edge(
                    "requests",
                    f"pass:{pass_id}",
                    node_id,
                    passes=[pass_id],
                    disposition=requested[source]["disposition"],
                )
        for checked, source in checked_targets.items():
            for dep_path in checked_deps[checked]:
                if not dep_path.endswith(".checked"):
                    continue
                dep_source = checked_targets.get(dep_path)
                if dep_source is None:
                    self.graph.finding(
                        "dependency-without-target",
                        f"pass {pass_id}: {source} depends on {dep_path} which has no target entry",
                        pass_id=pass_id,
                    )
                    continue
                self.imports[f"source:{source}"].add(f"source:{dep_source}")
                self.graph.edge(
                    "imports",
                    f"source:{source}",
                    f"source:{dep_source}",
                    passes=[pass_id],
                    granularity="module",
                )
        implementations = {
            (self.graph.nodes[f"source:{s}"]["module"]): f"source:{s}"
            for s in checked_targets.values()
            if self.graph.nodes[f"source:{s}"]["role"] == "implementation"
        }
        for source in checked_targets.values():
            node = self.graph.nodes[f"source:{source}"]
            if node["role"] == "interface" and node["module"] in implementations:
                implementation = implementations[node["module"]]
                self.satisfied_by[f"source:{source}"].add(implementation)
                self.graph.edge(
                    "satisfied-by",
                    f"source:{source}",
                    implementation,
                    passes=[pass_id],
                    granularity="module",
                )
        for source, entry in requested.items():
            if f"source:{source}" not in self.graph.nodes:
                raise GraphError(
                    f"pass {pass_id}: requested {entry['path']} is absent from the "
                    "dependency output"
                )
        self.record_shadow_scan(pass_id, cwd, checked_targets)

    def same_named_source_exists(self, checked: str, source: str) -> bool:
        candidate = self.local(os.path.dirname(checked)) / Path(source).name
        return candidate.is_file()

    def ensure_shadow_target(self, checked: str) -> str:
        source = checked.removesuffix(".checked")
        node_id = f"source:{source}"
        if node_id not in self.graph.nodes:
            module = Path(source).name.removesuffix(".fsti").removesuffix(".fst")
            self.graph.node(
                node_id,
                "source",
                module=module,
                role=admission.source_role(source),
                origin=self.origin(source),
                shadowed=True,
            )
        return node_id

    def cwd_source_digest(
        self, pass_id: str, source: str, recorded: str | None, origin: str
    ) -> str:
        if origin == "builder-generated":
            expected = self.loops_text()
            actual = digest_text(expected)
            if recorded is None:
                raise GraphError(f"pass {pass_id}: builder-generated {source} is not in the record")
            if recorded != actual:
                raise GraphError(
                    f"pass {pass_id}: recorded {source} ({recorded}) differs from the generator "
                    f"output ({actual})"
                )
            self.inputs.source_texts[source] = expected
            return actual
        path = self.local(source)
        if not path.is_file():
            raise GraphError(f"pass {pass_id}: recorded source {source} is not present locally")
        actual = digest_file(path)
        if recorded is None:
            raise GraphError(
                f"pass {pass_id}: {source} is in the closure but not in the recorded context"
            )
        if actual != recorded:
            raise GraphError(f"pass {pass_id}: {source} differs from its recorded digest")
        self.inputs.source_texts.setdefault(source, path.read_text(errors="replace"))
        return actual

    def loops_text(self) -> str:
        driver = self.inputs.driver
        text = regenerate_loops(driver.read_text())
        self.graph.node(
            "generator:verify_fstar.sh#C.Loops",
            "generator",
            path="scripts/flake/verify_fstar.sh",
            sha256=digest_file(driver),
            output_sha256=digest_text(text),
        )
        return text

    def retained_dependency_digest(
        self, pass_id: str, recorded_path: str, expected: str | None
    ) -> str:
        """Compare retained identities before reading source or loaded cache bytes."""
        path = self.local(recorded_path)
        if not path.is_file():
            raise GraphError(f"pass {pass_id}: dependency input missing: {recorded_path}")
        if expected is None and not (
            Path(recorded_path).is_relative_to("/nix/store")
            and path.resolve().is_relative_to("/nix/store")
        ):
            raise GraphError(
                f"pass {pass_id}: mutable dependency has no recorded digest: {recorded_path}"
            )
        actual = digest_file(path)
        if expected is not None and actual != expected:
            raise GraphError(
                f"pass {pass_id}: dependency differs from its recorded digest: {recorded_path}"
            )
        return actual

    def load_mode(
        self,
        pass_id: str,
        source: str,
        checked: str,
        module: str,
        role: str,
        requested: dict[str, dict[str, Any]],
        load: dict[str, Any],
    ) -> dict[str, Any]:
        checked_state = (
            "stale"
            if checked in load["stale"]
            else "loaded"
            if checked in load["loaded"]
            else "absent"
            if checked in load["attempted"]
            else "not-attempted"
        )
        key = f"{module}#{role}"
        if source in requested:
            if pass_id not in self.batch_traces:
                verified_key = key
                if requested[source]["disposition"] == "paired-interface":
                    implementation = source.removesuffix(".fsti") + ".fst"
                    if implementation not in requested:
                        raise GraphError(
                            f"pass {pass_id}: requested interface lacks its implementation"
                        )
                    verified_key = f"{module}#implementation"
                if (
                    key in load["lax"]
                    or verified_key in load["lax"]
                    or verified_key not in load["verified"]
                    # A successful cache read may be discarded before a source
                    # recheck. A later cache read cannot establish that ordering.
                    or load["loaded_lines"].get(checked, 0)
                    >= load["verified_lines"].get(verified_key, 0)
                ):
                    raise GraphError(
                        f"pass {pass_id}: requested source has no positive non-lax "
                        f"source verification: {source}"
                    )
            mode = "requested-verified"
        elif checked_state == "loaded":
            mode = "checked-artifact"
        elif key in load["lax"]:
            mode = "lax-source"
        elif key in load["verified"]:
            mode = "verified-dependency"
        elif checked_state == "stale":
            # A stale artifact must be followed by a source check; its absence is unexplained.
            mode = "unobserved"
        else:
            # Absence from the load trace is not positive evidence of non-use, even
            # for an implementation with an interface (friend can expose its body).
            mode = "unknown-source"
        if mode == "unobserved" and pass_id not in self.batch_traces:
            self.graph.finding(
                "load-mode-unresolved",
                f"pass {pass_id}: no load evidence for {source}",
                pass_id=pass_id,
            )
        result = {"mode": mode, "checked": checked_state}
        if checked_state == "stale":
            result["stale_reason"] = load["stale"][checked]
        return result

    def record_shadow_scan(self, pass_id: str, cwd: str, checked_targets: dict[str, str]) -> None:
        includes = self.graph.nodes[f"pass:{pass_id}"]["include_paths"]
        directories = [normalize_path(cwd, d) for d in includes]
        scan: dict[str, str] = {}
        for directory in directories:
            scan[directory] = "scanned" if self.local(directory).is_dir() else "unavailable"
            if scan[directory] == "unavailable":
                raise GraphError(f"pass {pass_id}: include directory {directory} is not readable")
        self.graph.nodes[f"pass:{pass_id}"]["include_scan"] = scan
        for source in checked_targets.values():
            node = self.graph.nodes[f"source:{source}"]
            if node["origin"] not in CWD_ORIGINS:
                continue
            name = Path(source).name
            for directory in directories:
                candidate = f"{directory}/{name}"
                if candidate == source:
                    continue
                if (self.local(directory) / name).is_file():
                    self.graph.edge(
                        "shadows",
                        f"source:{source}",
                        self.ensure_shadow_target(candidate + ".checked"),
                        passes=[pass_id],
                        evidence=["same file name in a searched include directory"],
                    )

    # -- premises --

    def declare_premises(self) -> None:
        for node_id, node in list(self.graph.nodes.items()):
            if node["kind"] != "source":
                continue
            source = node_id.removeprefix("source:")
            module = node["module"]
            for pass_id, mode in node.get("load_modes", {}).items():
                if node["origin"] == "builder-generated":
                    # Its whole content is the injected declarations recorded below.
                    continue
                if mode["mode"] in ("unknown-source", "dependency-scan"):
                    kind = (
                        "unknown-load" if mode["mode"] == "unknown-source" else "dependency-source"
                    )
                    premise_id = f"premise:{kind}:{module}#{node['role']}"
                    self.graph.node(
                        premise_id,
                        "premise",
                        premise_kind=kind,
                        module=module,
                        role=node["role"],
                        origin=node["origin"],
                    )
                    self.declare(node_id, premise_id)
                elif mode["mode"] in ("lax-source", "verified-dependency"):
                    premise_id = f"premise:lax-module:{module}#{node['role']}"
                    attrs: dict[str, Any] = {
                        "premise_kind": "lax-module",
                        "module": module,
                        "role": node["role"],
                        "origin": node["origin"],
                        "verified_elsewhere": sorted(
                            p
                            for p, m in node.get("load_modes", {}).items()
                            if m["mode"] == "requested-verified"
                        ),
                    }
                    if mode.get("stale_reason"):
                        attrs["stale_reason"] = mode["stale_reason"]
                    self.graph.node(premise_id, "premise", **attrs)
                    self.graph.nodes[premise_id].setdefault("passes", [])
                    if pass_id not in self.graph.nodes[premise_id]["passes"]:
                        self.graph.nodes[premise_id]["passes"].append(pass_id)
                        self.graph.nodes[premise_id]["passes"].sort()
                    self.declare(node_id, premise_id)
                elif mode["mode"] == "checked-artifact":
                    premise_id = f"premise:checked-import:{node['origin']}"
                    self.graph.node(
                        premise_id, "premise", premise_kind="checked-import", origin=node["origin"]
                    )
                    modules = self.graph.nodes[premise_id].setdefault("modules", [])
                    if f"{module}#{node['role']}" not in modules:
                        modules.append(f"{module}#{node['role']}")
                        modules.sort()
                    self.declare(node_id, premise_id)
            if node["origin"] not in CWD_ORIGINS or node.get("shadowed"):
                continue
            text = self.inputs.source_texts.get(source)
            if text is None:
                raise GraphError(f"no text for {source}")
            parsed = parse_fstar_source(text)
            self.parsed[node_id] = parsed
            node["declarations"] = parsed["imports"]
            for premise in parsed["premises"]:
                kind = premise["kind"]
                if node["origin"] == "builder-generated" and kind == "assume-val":
                    kind = "builder-injected"
                premise_id = f"premise:{module}#{premise['name']}"
                self.graph.node(
                    premise_id,
                    "premise",
                    premise_kind=kind,
                    module=module,
                    name=premise["name"],
                    line=premise["line"],
                    statement_sha256=digest_text(premise["statement"]),
                    statement=premise["statement"],
                )
                self.declare(node_id, premise_id)
                if kind == "builder-injected":
                    self.graph.edge("generated-by", node_id, "generator:verify_fstar.sh#C.Loops")
                if kind == "friend-exposure":
                    self.graph.edge(
                        "exposes", node_id, self.module_node(premise["name"].split(":", 1)[1])
                    )

    def declare(self, source_id: str, premise_id: str) -> None:
        self.graph.edge("declares", source_id, premise_id)
        if premise_id not in self.declares_by_source[source_id]:
            self.declares_by_source[source_id].append(premise_id)

    def module_node(self, module: str) -> str:
        for node_id, name in self.module_of.items():
            if name == module and self.graph.nodes[node_id]["role"] == "implementation":
                return node_id
        for node_id, name in self.module_of.items():
            if name == module:
                return node_id
        raise GraphError(f"friend target {module} is not in any pass closure")

    # -- register, matrix, contract --

    def register_entries(self) -> None:
        entries = self.inputs.register.get("entries")
        if not isinstance(entries, list):
            raise GraphError("register has no entries list")
        seen: set[str] = set()
        for entry in entries:
            entry_id = entry.get("id")
            if not isinstance(entry_id, str) or not entry_id:
                raise GraphError("register entry without id")
            if entry_id in seen:
                raise GraphError(f"duplicate register entry {entry_id}")
            seen.add(entry_id)
            node_id = f"register:{entry_id}"
            self.graph.node(
                node_id,
                "register-entry",
                register_kind=entry.get("kind"),
                status=entry.get("status"),
                title=entry.get("title"),
            )
            if entry.get("kind") in ("computational", "symbolic-abstraction"):
                premise_id = f"premise:{entry_id}"
                self.graph.node(
                    premise_id,
                    "premise",
                    premise_kind=entry["kind"],
                    events=entry.get("events", []),
                    statement=entry.get("statement"),
                )
                self.graph.edge("registers", node_id, premise_id)
                self.bind_events(entry, premise_id)
            premise_ids = list(entry.get("premise_ids", []))
            if entry.get("kind") in ("computational", "symbolic-abstraction"):
                premise_ids.append(f"premise:{entry_id}")
            for premise_id in entry.get("premise_ids", []):
                if premise_id in self.graph.nodes:
                    self.graph.edge("registers", node_id, premise_id)
            for property_id in entry.get("justified_by", []):
                if property_id not in self.graph.nodes:
                    self.graph.node(property_id, "property", declared=None)
                for premise_id in premise_ids:
                    if premise_id in self.graph.nodes:
                        self.graph.edge("justified-by", premise_id, property_id, register=entry_id)

    def bind_events(self, entry: dict[str, Any], premise_id: str) -> None:
        """Resolve every named event to fixed source bytes; retain module-level breadth."""
        for event in entry["events"]:
            module, _, symbol = event.rpartition(".")
            matches = []
            for source_id, name in self.module_of.items():
                if name != module or self.graph.nodes[source_id].get("shadowed"):
                    continue
                text = self.inputs.source_texts.get(source_id.removeprefix("source:"))
                if text is not None and declares_symbol(admission.strip_comments(text), symbol):
                    matches.append(source_id)
            if not matches:
                raise GraphError(
                    f"register {entry['id']}: event {event} has no declaration in the fixed closure"
                )
            for source_id in matches:
                self.graph.edge(
                    "interprets", premise_id, source_id, events=[event], granularity="module"
                )
                self.interpretation_by_source[source_id].add(premise_id)

    def matrix_properties(self) -> None:
        groups = {
            g["matrix_key"]: g.get("guarantee_ids", [])
            for g in self.inputs.contract["matrix_groups"]
        }
        for key, rows in self.inputs.matrix.items():
            if key == "metadata" or not isinstance(rows, list):
                continue
            for row in rows:
                row_id = row.get("id")
                if not isinstance(row_id, str):
                    raise GraphError(f"matrix row without id in {key}")
                proofs = row.get("proof") or []
                if not any(p.get("type") in ("fstar", "hacl", "tamarin", "kani") for p in proofs):
                    continue
                matrix_id = f"matrix:{row_id}"
                self.graph.node(matrix_id, "matrix", status=row.get("status"), group=key)
                for guarantee in groups.get(key, []):
                    self.graph.node(f"guarantee:{guarantee}", "guarantee")
                    self.graph.edge("guarantees", matrix_id, f"guarantee:{guarantee}")
                for proof in proofs:
                    self.cite(matrix_id, proof)

    def cite(self, matrix_id: str, proof: dict[str, Any]) -> None:
        kind = proof.get("type")
        if kind in ("fstar", "hacl"):
            file = proof.get("file")
            if not isinstance(file, str) or not file.endswith((".fst", ".fsti")):
                return
            names: list[str] = []
            for field in ("lemma", "invariant", "computation", "primitive"):
                value = proof.get(field)
                if isinstance(value, str):
                    names.extend(n for n in re.split(r"[,\s]+", value) if n)
            recorded = f"{self.recorded_root}/{file}"
            source_id = f"source:{recorded}"
            module = Path(file).name.removesuffix(".fsti").removesuffix(".fst")
            for name in names or ["*"]:
                property_id = f"property:{module}#{name}"
                declared: bool | None = None
                text = self.inputs.source_texts.get(recorded)
                if text is not None and name != "*":
                    declared = declares_symbol(admission.strip_comments(text), name)
                self.graph.node(
                    property_id, "property", module=module, name=name, declared=declared
                )
                self.graph.edge("cites", matrix_id, property_id, proof_type=kind)
                if source_id in self.graph.nodes:
                    self.graph.edge("defined-in", property_id, source_id)
                else:
                    self.graph.finding(
                        "cited-module-not-in-closure",
                        f"{matrix_id} cites {file}#{name} but no pass verified that file",
                    )
        elif kind == "tamarin":
            file = proof.get("file")
            lemmas = proof.get("lemma")
            if not isinstance(file, str) or not isinstance(lemmas, str):
                return
            theory = file.removeprefix("proofs/tamarin/")
            for lemma in (n for n in re.split(r"[,\s]+", lemmas) if n):
                lemma_id = f"tamarin:{theory}#{lemma}"
                self.graph.node(lemma_id, "tamarin-lemma", theory=theory, name=lemma)
                self.graph.edge("cites", matrix_id, lemma_id, proof_type="tamarin")

    def link_properties(self) -> None:
        defined_in = {
            e["from"]: e["to"] for e in self.graph.edges.values() if e["kind"] == "defined-in"
        }
        for node_id in list(self.graph.nodes):
            if self.graph.nodes[node_id]["kind"] != "property" or node_id not in defined_in:
                continue
            source_id = defined_in[node_id]
            direct = self.closure(source_id, through_interfaces=False)
            closure = self.closure(source_id, through_interfaces=True)
            own_text = self.parsed.get(source_id, {}).get("text", "")
            passes = sorted(self.graph.nodes[source_id].get("load_modes", {}))
            for tool in ("fstar", "solver"):
                self.graph.edge(
                    "depends-on",
                    node_id,
                    f"premise:tool:{tool}",
                    granularity="module-closure",
                    exact=False,
                    dependency_class="tool-trust",
                    passes=passes,
                )
            for member in sorted(closure):
                for premise_id in sorted(self.interpretation_by_source.get(member, set())):
                    self.graph.edge(
                        "depends-on",
                        node_id,
                        premise_id,
                        granularity="module-closure",
                        exact=False,
                        dependency_class="security-interpretation",
                        via=self.graph.nodes[member]["module"],
                    )
                for premise_id in self.declares_by_source.get(member, []):
                    premise = self.graph.nodes[premise_id]
                    attrs: dict[str, Any] = {
                        "granularity": "module-closure",
                        "exact": False,
                        "via": self.graph.nodes[member]["module"],
                        "through": "import" if member in direct else "interface-satisfaction",
                    }
                    name = premise.get("name")
                    if isinstance(name, str) and re.search(rf"\b{re.escape(name)}\b", own_text):
                        attrs["explicit_call"] = True
                    self.graph.edge("depends-on", node_id, premise_id, **attrs)

    def closure(self, source_id: str, *, through_interfaces: bool) -> set[str]:
        """Transitive imports; optionally also the implementations behind imported interfaces."""
        seen: set[str] = set()
        stack = [source_id]
        while stack:
            current = stack.pop()
            if current in seen:
                continue
            seen.add(current)
            stack.extend(self.imports.get(current, ()))
            if through_interfaces:
                stack.extend(self.satisfied_by.get(current, ()))
        return seen

    # -- Tamarin and Kani --

    def tamarin(self) -> None:
        selection = tamarin_selection(self.inputs.tamarin_script.read_text())
        script_sha = digest_file(self.inputs.tamarin_script)
        self.graph.node(
            "premise:tamarin-symbolic-model",
            "premise",
            premise_kind="tamarin-model",
            selection_sha256=script_sha,
        )
        for theory, lemmas in sorted(selection.items()):
            path = self.inputs.proofs_root / theory
            if not within(self.inputs.proofs_root, path) or not path.is_file():
                raise GraphError(f"Tamarin theory {theory} is not under the proofs root")
            parsed = parse_theory(path.read_text(errors="replace"))
            theory_id = f"tamarin:{theory}"
            self.graph.node(theory_id, "tamarin-theory", sha256=digest_file(path))
            premises: list[str] = []
            for builtin in parsed["builtins"]:
                premises.append(self.tamarin_premise(theory, "builtin", builtin))
            for function in parsed["functions"]:
                premises.append(self.tamarin_premise(theory, "function", function))
            for equation in parsed["equations"]:
                premises.append(self.tamarin_premise(theory, "equation", equation))
            for restriction in parsed["restrictions"]:
                premises.append(self.tamarin_premise(theory, "restriction", restriction))
            selected = lemmas or parsed["lemmas"]
            for lemma in selected:
                if lemma not in parsed["lemmas"]:
                    raise GraphError(f"Tamarin lemma {lemma} is not declared in {theory}")
                lemma_id = f"tamarin:{theory}#{lemma}"
                self.graph.node(lemma_id, "tamarin-lemma", theory=theory, name=lemma, selected=True)
                self.graph.edge("selects", theory_id, lemma_id)
                self.graph.edge(
                    "tamarin-uses", lemma_id, "premise:tamarin-symbolic-model", granularity="theory"
                )
                for premise_id in premises:
                    self.graph.edge("tamarin-uses", lemma_id, premise_id, granularity="theory")

    def tamarin_premise(self, theory: str, kind: str, text: str) -> str:
        token = text if kind in ("builtin", "restriction") else digest_text(text)[:16]
        premise_id = f"premise:tamarin:{theory}#{kind}:{token}"
        self.graph.node(
            premise_id, "premise", premise_kind=f"tamarin-{kind}", theory=theory, text=text
        )
        return premise_id

    def kani(self) -> None:
        kani = self.inputs.kani
        self.graph.node(
            "premise:kani-bounded-model",
            "premise",
            premise_kind="kani-model",
            kani_version=kani.get("kani_version"),
            solver=kani.get("solver"),
            target=kani.get("target"),
            toolchain_sha256=kani.get("toolchain", {}).get("rust_toolchain_toml_sha256"),
        )
        for group in kani.get("groups", []):
            group_id = group.get("id")
            harnesses = group.get("harnesses")
            if not isinstance(group_id, str) or not isinstance(harnesses, list):
                continue
            node_id = f"kani:{group_id}"
            self.graph.node(
                node_id, "kani-group", **{k: group.get(k) for k in ("class", "gating", "crate")}
            )
            premises = [
                self.kani_premise(group_id, "features", group.get("features")),
                self.kani_premise(group_id, "cfg", group.get("cfg")),
                self.kani_premise(group_id, "unwind", group.get("default_unwind")),
            ]
            for harness in harnesses:
                name = harness.get("name")
                if not isinstance(name, str):
                    continue
                harness_id = f"kani:{group_id}#{name}"
                self.graph.node(harness_id, "kani-harness", file=harness.get("file"))
                self.graph.edge("selects", node_id, harness_id)
                self.graph.edge("kani-uses", harness_id, "premise:kani-bounded-model")
                for premise_id in premises:
                    self.graph.edge("kani-uses", harness_id, premise_id)
                for field in ("unwind", "unreachable_assertions"):
                    if field in harness:
                        self.graph.edge(
                            "kani-uses",
                            harness_id,
                            self.kani_premise(group_id, f"{field}@{name}", harness[field]),
                        )
                for row in harness.get("rows", []):
                    matrix_id = f"matrix:{row}"
                    if matrix_id in self.graph.nodes:
                        self.graph.edge("cites", matrix_id, harness_id, proof_type="kani")

    def kani_premise(self, group: str, field: str, value: Any) -> str:
        premise_id = f"premise:kani:{group}#{field}"
        self.graph.node(
            premise_id, "premise", premise_kind="kani-bound", group=group, field=field, value=value
        )
        return premise_id

    # -- assembly --

    def build(self) -> dict[str, Any]:
        pass_ids = self.inputs.pass_ids()
        for pass_id in pass_ids:
            self.process_pass(pass_id)
        self.declare_premises()
        self.matrix_properties()
        self.register_entries()
        self.link_properties()
        self.tamarin()
        self.kani()
        meta = {
            "schema_version": SCHEMA_VERSION,
            "contract": CONTRACT,
            "source_identity": self.source_identity,
            "passes": pass_ids,
            "admission_sha256": digest_file(self.inputs.evidence / "admission.json"),
            "register_sha256": digest_file(self.inputs.register_path),
        }
        return self.graph.body(meta)


def build_graph(
    evidence: Path, source_root: Path, register: Path, source_identity: str | None
) -> dict[str, Any]:
    return Builder(Inputs(evidence, source_root, register), source_identity).build()


def wrap(body: dict[str, Any]) -> dict[str, Any]:
    return {
        "body": body,
        "body_sha256": digest_text(canonical(body)),
        "created_at": datetime.now(UTC).isoformat(),
        "builder": file_identity(Path(__file__).resolve()),
    }


